    private static void ekle(String marka, String model, int yil, double tabanFiyat) {
        katalog.computeIfAbsent(marka.toLowerCase().trim(), k -> new HashMap<>())
               .computeIfAbsent(model.toLowerCase().trim(), k -> new HashMap<>())
               .put(yil, tabanFiyat);
    }

    /**
     * Marka, Model ve Yıla Göre Taban Fiyatı Getirir
     */
    public static double getTabanFiyat(String marka, String model, int yil) {
        String markaKey = marka.toLowerCase().trim();
        String modelKey = model.toLowerCase().trim();

        if (katalog.containsKey(markaKey) && katalog.get(markaKey).containsKey(modelKey)) {
            Map<Integer, Double> yilMap = katalog.get(markaKey).get(modelKey);

            // Aranılan yıl katalogda birebir varsa
            if (yilMap.containsKey(yil)) {
                return yilMap.get(yil);
            }
            // Yoksa katalogdaki en yakın yıldan türet
            return enYakinYildanTuret(yilMap, yil);
        }

        // Katalogda henüz kayıtlı olmayan marka/modeller için genel ortalama taban fiyat
        return 900000.0;
    }

    private static double enYakinYildanTuret(Map<Integer, Double> yilMap, int hedefYil) {
        int enYakinYil = yilMap.keySet().iterator().next();
        int minFark = Math.abs(hedefYil - enYakinYil);

        for (int y : yilMap.keySet()) {
            int fark = Math.abs(hedefYil - y);
            if (fark < minFark) {
                minFark = fark;
                enYakinYil = y;
            }
        }

        double bazFiyat = yilMap.get(enYakinYil);
        int yilFarki = hedefYil - enYakinYil;
        // Yıllık ortalama %7 piyasa değişim oranı
        return bazFiyat * Math.pow(1.07, yilFarki);
    }
